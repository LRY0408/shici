    exportRecords() {
        SoundManager.click();
        let data = {
            records: VocabStorage.get(),
            progress: VocabStorage.getProgress(),
            exportTime: new Date().toISOString(),
            version: '1.0'
        };
        let jsonStr = JSON.stringify(data, null, 2);
        let filename = 'shici_records_' + new Date().toISOString().slice(0,10) + '.json';
        
        try {
            let blob = new Blob([jsonStr], {type: 'application/json;charset=utf-8'});
            
            // 方法1：用a标签下载
            if (window.navigator && window.navigator.msSaveOrOpenBlob) {
                // IE/Edge
                window.navigator.msSaveOrOpenBlob(blob, filename);
            } else {
                // 其他浏览器
                let url = URL.createObjectURL(blob);
                let a = document.createElement('a');
                a.href = url;
                a.download = filename;
                a.style.display = 'none';
                document.body.appendChild(a);
                
                // 触发点击
                a.click();
                
                // 延迟清理
                setTimeout(() => {
                    document.body.removeChild(a);
                    URL.revokeObjectURL(url);
                }, 2000);
            }
            
            // 计算已学单词总数
            let r = data.records;
            let wordCount = 0;
            for (let listKey in r.learned) { wordCount += Object.keys(r.learned[listKey]).length; }
            
            alert('学习记录已导出！\n文件名：' + filename + '\n共 ' + wordCount + ' 个已学单词，' + r.quizCount + ' 次测验。\n\n如果没有自动下载，请检查浏览器下载管理，或允许浏览器下载文件。');
            
        } catch(err) {
            alert('导出失败：' + err.message + '\n\n请尝试以下方法：\n1. 检查浏览器是否允许下载文件\n2. 尝试用其他浏览器打开\n3. 联系开发者');
        }
    }

    importRecords(event) {
        let file = event.target.files[0];
        if (!file) return;
        // 验证文件类型
        if (!file.name.endsWith('.json') && file.type !== 'application/json') {
            alert('请选择拾词导出的JSON文件！');
            event.target.value = '';
            return;
        }
        let reader = new FileReader();
        reader.onload = (e) => {
            try {
                let data = JSON.parse(e.target.result);
                // 验证数据格式
                if (!data.records || !data.records.learned) {
                    throw new Error('格式不正确');
                }
                // 保存记录
                localStorage.setItem(VocabStorage.KEY, JSON.stringify(data.records));
                // 保存进度（如果有）
                if (data.progress) {
                    localStorage.setItem(VocabStorage.PROGRESS_KEY, JSON.stringify(data.progress));
                }
                SoundManager.correct();
                // 计算已学单词总数
                let wordCount = 0;
                for (let listKey in data.records.learned) { wordCount += Object.keys(data.records.learned[listKey]).length; }
                alert('学习记录导入成功！\n共恢复 ' + wordCount + ' 个已学单词，' + data.records.quizCount + ' 次测验。');
                // 刷新页面数据
                this.renderRecords();
                this.updateHomeStats();
                this.renderSelectPage();
                this.checkContinueProgress();
            } catch(err) {
                SoundManager.wrong();
                alert('导入失败：文件格式不正确，请确认是拾词导出的JSON文件。\n错误信息：' + err.message);
            }
        };
        reader.onerror = () => {
            alert('文件读取失败，请重试！');
        };
        reader.readAsText(file);
        event.target.value = '';
    }

    updateSoundIcon() { let btn = document.getElementById('sound-toggle'); if (btn) { btn.textContent = SoundManager.enabled ? '🔊' : '🔇'; } }
    toggleSound() { let enabled = SoundManager.toggle(); this.updateSoundIcon(); if (enabled) SoundManager.click(); }

    bindEnterKey() {
        document.addEventListener('keydown', (e) => {
            if (e.key !== 'Enter') return;
            let reviewPage = document.getElementById('page-review');
            let quizDoing = document.getElementById('quiz-doing');
            let handleEnter = (inputsId, submitFn) => {
                let inputs = document.querySelectorAll('#' + inputsId + ' .meaning-input');
                let activeEl = document.activeElement;
                let idx = -1;
                for (let i = 0; i < inputs.length; i++) { if (inputs[i] === activeEl) { idx = i; break; } }
                if (idx >= 0 && idx < inputs.length - 1) { e.preventDefault(); inputs[idx + 1].focus(); inputs[idx + 1].select(); }
                else { submitFn(); }
            };
            if (reviewPage.classList.contains('active')) {
                if (!this.review.submitted) handleEnter('review-inputs', () => this.submitAnswer());
                else this.nextWord();
            } else if (quizDoing && !quizDoing.classList.contains('hidden')) {
                handleEnter('quiz-inputs', () => this.submitQuizAnswer());
            }
        });
    }
