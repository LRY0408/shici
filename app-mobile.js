class ReviewSession {
    constructor() { this.words = []; this.index = 0; this.submitted = false; this.order = 'sequential'; this.answers = []; }
    setOrder(order) { this.order = order; }
    start(listKeys, startIndex = 0) {
        this.words = [];
        listKeys.forEach(listKey => { window.CLEAN_DATA[listKey].forEach(w => this.words.push({...w, listKey})); });
        if (this.order === 'random') this.shuffle();
        this.index = startIndex;
        this.submitted = false;
    }
    shuffle() { for (let i = this.words.length - 1; i > 0; i--) { let j = Math.floor(Math.random() * (i + 1)); [this.words[i], this.words[j]] = [this.words[j], this.words[i]]; } }
    get current() { return this.words[this.index]; }
    get isFirst() { return this.index === 0; }
    get isLast() { return this.index === this.words.length - 1; }
    next() { if (!this.isLast) { this.index++; this.submitted = false; return true; } return false; }
    prev() { if (!this.isFirst) { this.index--; this.submitted = false; return true; } return false; }
    submit(correct) { this.submitted = true; this.answers.push({word: this.current.word, correct: correct}); VocabStorage.markLearned(this.current.listKey, this.current.word); }
}

// ============ 测验会话 ============
class QuizSession {
    constructor() { this.words = []; this.index = 0; this.answers = []; this.count = 10; }
    setCount(count) { this.count = count; }
    start() {
        let learned = VocabStorage.getLearnedWords();
        for (let i = learned.length - 1; i > 0; i--) { let j = Math.floor(Math.random() * (i + 1)); [learned[i], learned[j]] = [learned[j], learned[i]]; }
        this.words = learned.slice(0, Math.min(this.count, learned.length));
        this.index = 0;
        this.answers = [];
    }
    get current() { return this.words[this.index]; }
    get isLast() { return this.index === this.words.length - 1; }
    submitAnswer(userAnswers, correct) { this.answers.push({word: this.current, userAnswers, correct, meanings: WordProcessor.splitMeanings(this.current.meaning)}); }
    next() { if (!this.isLast) { this.index++; return true; } return false; }
    get result() { let correctCount = this.answers.filter(a => a.correct).length; let accuracy = this.answers.length > 0 ? Math.round(correctCount / this.answers.length * 100) : 0; return {correctCount, total: this.answers.length, accuracy, wrongAnswers: this.answers.filter(a => !a.correct)}; }
    saveResult() { let r = VocabStorage.get(); r.quizCount++; r.totalCorrect += this.result.correctCount; r.totalAnswered += this.result.total; VocabStorage.save(r); }
}

