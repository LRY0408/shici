    submitQuizAnswer() {
        if (document.getElementById('quiz-doing').classList.contains('hidden')) return;
        let w = this.quiz.current;
        let meanings = WordProcessor.splitMeanings(w.meaning);
        let inputs = document.querySelectorAll('#quiz-inputs .meaning-input');
        let correct = true;
        let userAnswers = [];
        let usedMeanings = new Set();
        inputs.forEach((inp) => {
            let userAns = inp.value.trim();
            userAnswers.push(userAns);
            let matched = false;
            for (let i = 0; i < meanings.length; i++) {
                if (!usedMeanings.has(i) && WordProcessor.isAnswerCorrect(userAns, meanings[i])) { usedMeanings.add(i); matched = true; break; }
            }
            if (!matched) correct = false;
        });
        if (correct) {
            SoundManager.correct();
            // 做对了，从错题本移除
            VocabStorage.removeWrongWord(w.word);
        } else {
            SoundManager.wrong();
            // 做错了，记录到错题本，频次+1
            VocabStorage.addWrongWord(w.word, w.listKey);
        }
        this.quiz.submitAnswer(userAnswers, correct);
        if (this.quiz.next()) this.renderQuizWord();
        else { SoundManager.complete(); this.showQuizResult(); }
    }
